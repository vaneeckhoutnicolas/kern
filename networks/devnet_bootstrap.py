"""
devnet_bootstrap.py
===================

Generate a local Kern devnet: N validators, each with its own keypair, a
shared genesis with all of them pre-funded and registered as validators,
and a docker-compose file that runs them (one container each), the
Heimdall explorer, and optionally Prometheus and Grafana.

Most people should use the launcher, which calls this module:

    python scripts/devnet.py up [--validators N] [--monitoring]

Direct use:

    python networks/devnet_bootstrap.py --validators 4 --out networks/devnet [--monitoring]

This writes:
    networks/devnet/
        genesis.json                     # shared genesis
        keys/baker0.json … bakerN-1.json # validator keypairs (public test keys)
        keys/faucet.json                 # extra funded account for test transfers
        docker-compose.yml               # validators, Heimdall, monitoring
        prometheus.yml                   # with --monitoring
        README.md                        # how to start, query, stop

See docs/devnet.md.
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import time
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from kern.crypto import KernKeypair


def write_keypair(path: Path, seed_hex: str) -> dict:
    kp = KernKeypair.from_seed(bytes.fromhex(seed_hex))
    data = {
        "address": kp.address,
        "public_key": kp.public_key_b58,
        "seed_hex": seed_hex,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    return data


# Ports published on this machine's loopback only (127.0.0.1).
BASE_RPC_PORT = 18732          # baker i -> BASE_RPC_PORT + i
EXPLORER_PORT = 8800           # Heimdall
PROMETHEUS_PORT = 9090
GRAFANA_PORT = 3000
# One image for every node and for Heimdall (docker/Dockerfile).
IMAGE = "kern-devnet:local"
# Monitoring images, pinned like kern_explorer/monitoring/docker.
PROMETHEUS_IMAGE = "prom/prometheus:v2.51.0"
GRAFANA_IMAGE = "grafana/grafana:10.4.0"


def prometheus_config(names: list, explorer: bool) -> str:
    """Prometheus scrape configuration for the devnet: every node's
    /metrics, and Heimdall's when it runs."""
    lines = ["# Generated by networks/devnet_bootstrap.py",
             "global:",
             "  scrape_interval: 5s",
             "  evaluation_interval: 15s",
             "rule_files:",
             "  - /etc/prometheus/rules/*.yml",
             "scrape_configs:",
             "  - job_name: kern_node",
             "    metrics_path: /metrics",
             "    static_configs:"]
    for name in names:
        lines += [f"      - targets: ['{name}:8732']",
                  f"        labels: {{node: '{name}', role: validator}}"]
    if explorer:
        lines += ["  - job_name: heimdall",
                  "    metrics_path: /metrics",
                  "    static_configs:",
                  "      - targets: ['heimdall:8800']",
                  "        labels: {service: heimdall, role: explorer}"]
    return "\n".join(lines) + "\n"


def build(out_dir: Path, n_validators: int, initial_stake: int,
          initial_balance: int, faucet_balance: int, *,
          explorer: bool = True, monitoring: bool = False) -> None:
    keys_dir = out_dir / "keys"
    keys_dir.mkdir(parents=True, exist_ok=True)

    validators = []
    balances = {}
    # Validators
    for i in range(n_validators):
        seed = f"{i + 1:02x}" * 32
        data = write_keypair(keys_dir / f"baker{i}.json", seed)
        validators.append({
            "address": data["address"],
            "pubkey": data["public_key"],
            "stake": initial_stake,
        })
        balances[data["address"]] = initial_balance

    # Faucet
    faucet = write_keypair(keys_dir / "faucet.json", "fa" * 32)
    balances[faucet["address"]] = faucet_balance

    # Treasury
    treasury = write_keypair(keys_dir / "treasury.json", "7e" * 32)
    balances[treasury["address"]] = 0  # filled by issuance

    genesis = {
        "chain_id": "kern-devnet",
        "timestamp": int(time.time()),
        # Same placeholder convention as scripts/build_genesis.py: the
        # genesis block is accepted because it matches this file.
        "genesis_proposer": {"address": validators[0]["address"],
                             "pubkey": validators[0]["pubkey"]},
        "genesis_signature": "ksig" + "0" * 95,
        "balances": balances,
        "validators": validators,
        "treasury_address": treasury["address"],
        "issuance_params": None,
    }
    (out_dir / "genesis.json").write_text(json.dumps(genesis, indent=2), encoding="utf-8")

    # Docker-compose. One image (docker/Dockerfile) serves every node and
    # Heimdall; it is built once, under IMAGE. Each node runs a shell instead
    # of the image's entrypoint, to initialize its data volume on first start
    # and then start the node (`init` refuses, harmlessly, a volume that is
    # already initialized). Inside the container the RPC listens on every
    # interface so that the published port reaches it; the host publishes it
    # on its own loopback only. The peer-to-peer port stays on the compose
    # network.
    services: dict = {}
    base_rpc = BASE_RPC_PORT
    rpc_port, p2p_port = 8732, 9732
    repo_root = Path(__file__).resolve().parent.parent
    context = os.path.relpath(repo_root, out_dir.resolve())
    build_spec = {"context": context, "dockerfile": "docker/Dockerfile"}
    names = [f"baker{i}" for i in range(n_validators)]

    for i, name in enumerate(names):
        start = ["python", "-m", "kern.node", "start",
                 "--data-dir", "/data",
                 "--rpc-port", str(rpc_port), "--rpc-bind", "0.0.0.0",
                 "--p2p-port", str(p2p_port),
                 "--baker-key", f"/keys/{name}.json",
                 "--block-time", "1.0"]
        for other in names:
            if other != name:
                start += ["--peer", f"{other}:{p2p_port}"]
        init = ["python", "-m", "kern.node", "init",
                "--genesis", "/genesis.json", "--data-dir", "/data"]
        services[name] = {
            "image": IMAGE,
            "entrypoint": ["sh", "-c"],
            # One list item: compose splits a plain string into words, and
            # `sh -c` would then run only the first one.
            "command": [f"{shlex.join(init)}; exec {shlex.join(start)}"],
            "volumes": [
                "./keys:/keys:ro",
                f"{name}-data:/data",
                "./genesis.json:/genesis.json:ro",
            ],
            "ports": [f"127.0.0.1:{base_rpc + i}:{rpc_port}"],
            "restart": "unless-stopped",
        }
        if i == 0:
            services[name]["build"] = build_spec
        else:
            # Built by baker0; never pulled from a registry.
            services[name]["pull_policy"] = "never"
            services[name]["depends_on"] = [names[0]]
    volumes: dict = {f"{name}-data": {} for name in names}

    if explorer:
        # Heimdall indexes the chain from baker0's RPC.
        services["heimdall"] = {
            "image": IMAGE,
            "pull_policy": "never",
            "entrypoint": ["python", "-c", "from kern_explorer.app import main; main()"],
            "environment": {
                "KERN_RPC": f"http://{names[0]}:{rpc_port}",
                "HEIMDALL_HOST": "0.0.0.0",
                "HEIMDALL_PORT": str(EXPLORER_PORT),
                "HEIMDALL_DB": "/data/heimdall.sqlite",
            },
            "volumes": ["heimdall-data:/data"],
            "ports": [f"127.0.0.1:{EXPLORER_PORT}:{EXPLORER_PORT}"],
            "depends_on": [names[0]],
            "restart": "unless-stopped",
        }
        volumes["heimdall-data"] = {}

    if monitoring:
        (out_dir / "prometheus.yml").write_text(prometheus_config(names, explorer),
                                                encoding="utf-8")
        mon = f"{context}/kern_explorer/monitoring"
        services["prometheus"] = {
            "image": PROMETHEUS_IMAGE,
            "command": ["--config.file=/etc/prometheus/prometheus.yml",
                        "--storage.tsdb.path=/prometheus"],
            "volumes": ["./prometheus.yml:/etc/prometheus/prometheus.yml:ro",
                        f"{mon}/alerts/kern-alerts.yml:/etc/prometheus/rules/kern-alerts.yml:ro",
                        "prometheus-data:/prometheus"],
            "ports": [f"127.0.0.1:{PROMETHEUS_PORT}:9090"],
            "depends_on": names,
            "restart": "unless-stopped",
        }
        services["grafana"] = {
            "image": GRAFANA_IMAGE,
            "volumes": [
                f"{mon}/docker/grafana-datasources.yml:/etc/grafana/provisioning/datasources/datasources.yml:ro",
                f"{mon}/docker/grafana-dashboards-provider.yml:/etc/grafana/provisioning/dashboards/dashboards.yml:ro",
                f"{mon}/grafana:/var/lib/grafana/dashboards:ro",
                "grafana-data:/var/lib/grafana",
            ],
            # Local devnet only: published on this machine's loopback.
            "environment": {"GF_SECURITY_ADMIN_USER": "admin",
                            "GF_SECURITY_ADMIN_PASSWORD": "admin",
                            "GF_USERS_ALLOW_SIGN_UP": "false"},
            "ports": [f"127.0.0.1:{GRAFANA_PORT}:3000"],
            "depends_on": ["prometheus"],
            "restart": "unless-stopped",
        }
        volumes["prometheus-data"] = {}
        volumes["grafana-data"] = {}

    compose = {"name": "kern-devnet", "services": services, "volumes": volumes}
    (out_dir / "docker-compose.yml").write_text(
        json.dumps(compose, indent=2), encoding="utf-8"
    )

    # README. The list is built outside the f-string: Python 3.11 refuses a
    # backslash inside an f-string expression.
    more_rpc = "".join(f"- baker{i} → http://localhost:{base_rpc + i}\n"
                       for i in range(2, n_validators))
    explorer_line = ", Heimdall explorer" if explorer else ""
    monitoring_line = ", Prometheus and Grafana" if monitoring else ""
    urls_extra = ""
    if explorer:
        urls_extra += f"- Heimdall explorer → http://localhost:{EXPLORER_PORT}\n"
    if monitoring:
        urls_extra += (f"- Prometheus → http://localhost:{PROMETHEUS_PORT}\n"
                       f"- Grafana → http://localhost:{GRAFANA_PORT} (admin / admin)\n")
    readme = f"""# Kern Devnet — {n_validators} validators

This is a local devnet bootstrap with {n_validators} validators that
will run in lock-step via BFT consensus, baking blocks every ~1 second.

## What's here

- `genesis.json`: chain genesis. {n_validators} validators, each with
  {initial_stake:,} mukrn stake and {initial_balance:,} starting balance.
  A faucet account with {faucet_balance:,} mukrn for distributing test
  tokens, and a treasury account that will fill from block rewards.
- `keys/baker0.json` … `baker{n_validators - 1}.json`: validator keypairs.
  **Devnet only — never use these for anything else.**
- `keys/faucet.json`: pre-funded account for sending test transfers.
- `keys/treasury.json`: the on-chain treasury (do not spend manually).
- `docker-compose.yml`: one container per validator{explorer_line}{monitoring_line}.

## Bring it up

From the repository root, the launcher does everything (generate if
needed, build, start, wait for the first blocks):

```bash
python scripts/devnet.py up
python scripts/devnet.py status   # head of every node
python scripts/devnet.py check    # every node holds the same block at every level
python scripts/devnet.py down     # stop (add --reset to delete the chain data)
```

Or by hand: `docker compose up -d --build` in this directory.

Each validator exposes its RPC on a different port of this machine
(published on 127.0.0.1 only):
- baker0 → http://localhost:{base_rpc + 0}
- baker1 → http://localhost:{base_rpc + 1}
{more_rpc}{urls_extra}

## Query

```bash
# Chain head
curl http://localhost:{base_rpc}/chain/head | jq

# Metrics (Prometheus format)
curl http://localhost:{base_rpc}/metrics

# Governance state
curl http://localhost:{base_rpc}/chain/governance | jq

# All RPC endpoints
curl http://localhost:{base_rpc}/chain/health
```

## Send a test transfer

```bash
python -c "
from kern.crypto import KernKeypair
from kern.transaction import make_transfer
import json, urllib.request

with open('keys/faucet.json') as f: faucet = json.load(f)
with open('keys/baker0.json') as f: dest = json.load(f)

kp = KernKeypair.from_seed(bytes.fromhex(faucet['seed_hex']))
tx = make_transfer(kp, dest['address'], 1_000_000, nonce=0)

body = json.dumps(tx.to_dict()).encode()
req = urllib.request.Request('http://localhost:{base_rpc}/chain/inject_transaction',
                              data=body, headers={{'Content-Type': 'application/json'}})
print(urllib.request.urlopen(req).read().decode())
"
```

## Tear down

```bash
python scripts/devnet.py down --reset   # or: docker compose down -v
```

## Status

Devnet is for contributor use only. Tokens have no value. Reset freely.
For the next step on the network track, see `docs/roadmap.md`
(Previewnet ← v0.9 ← here).
"""
    (out_dir / "README.md").write_text(readme, encoding="utf-8")
    print(f"Devnet bootstrap written to {out_dir}/")
    print(f"  - {n_validators} validators + 1 faucet + 1 treasury account")
    print(f"  - docker-compose with RPC ports {base_rpc}..{base_rpc + n_validators - 1}")
    print("  - Run: python scripts/devnet.py up")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--validators", type=int, default=3,
                    help="Number of validator nodes (default 3)")
    ap.add_argument("--out", type=Path, default=Path("networks/devnet"),
                    help="Output directory")
    ap.add_argument("--stake", type=int, default=1_000_000_000,
                    help="Initial stake per validator (mukrn)")
    ap.add_argument("--balance", type=int, default=5_000_000_000,
                    help="Initial balance per validator (mukrn)")
    ap.add_argument("--faucet", type=int, default=100_000_000_000,
                    help="Faucet balance (mukrn)")
    ap.add_argument("--no-explorer", action="store_true",
                    help="Do not add the Heimdall explorer")
    ap.add_argument("--monitoring", action="store_true",
                    help="Add Prometheus and Grafana (images from Docker Hub)")
    args = ap.parse_args()

    if args.validators < 1:
        ap.error("--validators must be at least 1")
    build(args.out, args.validators, args.stake, args.balance, args.faucet,
          explorer=not args.no_explorer, monitoring=args.monitoring)


if __name__ == "__main__":
    main()
